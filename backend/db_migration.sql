-- 1. Table: users
CREATE TABLE IF NOT EXISTS users (
    userid UUID PRIMARY KEY,
    username VARCHAR(255) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE,
    passhash VARCHAR(255),
    ghoauth VARCHAR(255),
    createdat TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    "Role" VARCHAR(255) NOT NULL DEFAULT 'Developer'
);

-- Ensure columns exist in case the table already existed but columns were added later
ALTER TABLE users ADD COLUMN IF NOT EXISTS username VARCHAR(255);
ALTER TABLE users ADD COLUMN IF NOT EXISTS email VARCHAR(255);
ALTER TABLE users ADD COLUMN IF NOT EXISTS passhash VARCHAR(255);
ALTER TABLE users ADD COLUMN IF NOT EXISTS ghoauth VARCHAR(255);
ALTER TABLE users ADD COLUMN IF NOT EXISTS createdat TIMESTAMP DEFAULT CURRENT_TIMESTAMP;
ALTER TABLE users ADD COLUMN IF NOT EXISTS "Role" VARCHAR(255) DEFAULT 'Developer';


